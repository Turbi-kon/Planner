@dataclass(frozen=True)
class GreetingParts:
    opening: str
    greeting: str
    wish: str
    extra: str
    ending: str


def random_parts(style: str = "funny", rng: random.Random | None = None) -> GreetingParts:
    if style not in BANKS:
        raise ValueError("Неизвестный стиль поздравления.")
    chooser = rng or random
    return GreetingParts(**{key: chooser.choice(options) for key, options in BANKS[style].items()})


def compose_greeting(name: str, parts: GreetingParts, birth_year: int | None = None,
                     current_year: int | None = None) -> str:
    name = name.strip()
    opening = f"{name}, {parts.opening} {parts.greeting}" if name else f"{parts.opening} {parts.greeting}"
    if not name:
        opening = opening[0].upper() + opening[1:]
    age_line = ""
    if birth_year is not None:
        year = date.today().year if current_year is None else current_year
        age = year - birth_year
        years = age_text(age)
        if age == 18:
            age_line = "Сегодня тебе 18 — с совершеннолетием! "
        elif age >= 20 and age % 5 == 0:
            age_line = f"Сегодня у тебя юбилей — {years}! "
        else:
            age_line = f"Сегодня тебе {years}! "
    return f"{opening}\n\n{age_line}{parts.wish} {parts.extra}\n\n{parts.ending}"
